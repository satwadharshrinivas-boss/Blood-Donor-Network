import os
import sqlite3
from flask import Flask, request, send_file

app = Flask(__name__)
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
USE_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))

if USE_POSTGRES:
    import psycopg
    from psycopg.rows import dict_row


def get_connection():
    """Use Neon/PostgreSQL when DATABASE_URL is set; otherwise use local SQLite."""
    if USE_POSTGRES:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10)
    conn = sqlite3.connect("donors.db")
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    conn = get_connection()
    try:
        with conn:
            if USE_POSTGRES:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS donors (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        mobile TEXT NOT NULL,
                        blood_group TEXT NOT NULL,
                        location TEXT NOT NULL,
                        availability TEXT NOT NULL,
                        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                """)
            else:
                conn.execute("""
                    CREATE TABLE IF NOT EXISTS donors (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        name TEXT NOT NULL,
                        mobile TEXT NOT NULL,
                        blood_group TEXT NOT NULL,
                        location TEXT NOT NULL,
                        availability TEXT NOT NULL,
                        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
                    )
                """)
    finally:
        conn.close()


@app.route("/")
def home():
    return send_file("index.html")


@app.route("/health")
def health():
    return {"status": "ok", "database": "neon-postgresql" if USE_POSTGRES else "local-sqlite"}


@app.route("/register", methods=["POST"])
def register_donor():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return {"error": "Donor information is required"}, 400

    fields = ["name", "mobile", "blood_group", "location", "availability"]
    cleaned = {field: str(data.get(field, "")).strip() for field in fields}
    missing = [field for field in fields if not cleaned[field]]
    if missing:
        return {"error": f"{missing[0]} is required"}, 400

    # Basic validation; a production version should add consent and privacy controls.
    if not cleaned["mobile"].replace("+", "").replace(" ", "").replace("-", "").isdigit():
        return {"error": "Please enter a valid mobile number"}, 400
    if cleaned["blood_group"] not in {"A+", "A-", "B+", "B-", "O+", "O-", "AB+", "AB-"}:
        return {"error": "Please select a valid blood group"}, 400
    if cleaned["availability"] not in {"Available", "Not Available"}:
        return {"error": "Please select a valid availability status"}, 400

    conn = get_connection()
    try:
        with conn:
            if USE_POSTGRES:
                conn.execute(
                    "INSERT INTO donors (name, mobile, blood_group, location, availability) VALUES (%s, %s, %s, %s, %s)",
                    tuple(cleaned[field] for field in fields),
                )
            else:
                conn.execute(
                    "INSERT INTO donors (name, mobile, blood_group, location, availability) VALUES (?, ?, ?, ?, ?)",
                    tuple(cleaned[field] for field in fields),
                )
    except Exception:
        app.logger.exception("Donor registration failed")
        return {"error": "Could not save donor details. Please try again."}, 500
    finally:
        conn.close()

    return {"message": "Donor registered successfully!"}, 201


@app.route("/search", methods=["GET"])
def search_donors():
    blood_group = request.args.get("blood_group", "").strip()
    location = request.args.get("location", "").strip()

    if blood_group and blood_group not in {"A+", "A-", "B+", "B-", "O+", "O-", "AB+", "AB-"}:
        return {"error": "Please select a valid blood group", "donors": []}, 400

    if USE_POSTGRES:
        query = "SELECT id, name, mobile, blood_group, location, availability FROM donors WHERE availability = %s"
        params = ["Available"]
        if blood_group:
            query += " AND blood_group = %s"
            params.append(blood_group)
        if location:
            query += " AND location ILIKE %s"
            params.append(f"%{location}%")
    else:
        query = "SELECT id, name, mobile, blood_group, location, availability FROM donors WHERE availability = ?"
        params = ["Available"]
        if blood_group:
            query += " AND blood_group = ?"
            params.append(blood_group)
        if location:
            query += " AND location LIKE ? COLLATE NOCASE"
            params.append(f"%{location}%")

    conn = get_connection()
    try:
        donors = conn.execute(query, params).fetchall()
        return {"donors": [dict(donor) for donor in donors]}
    except Exception:
        app.logger.exception("Donor search failed")
        return {"error": "Could not search donors. Please try again.", "donors": []}, 500
    finally:
        conn.close()


# Gunicorn imports this module, so initialize the table outside the __main__ block too.
init_db()

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", "5000")), debug=True)
